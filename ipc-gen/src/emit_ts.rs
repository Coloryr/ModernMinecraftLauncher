//! 生成前端 TS 文本：types/ 下的 DTO、bindings.ts 命令包装、listens.ts 事件订阅

use std::collections::{BTreeMap, BTreeSet};

use crate::{
    Decl, GeneratedFile, Sig,
    scan::{rename_all_of, split_top_level, ScannedEvent},
    ts::{camel, pascal, ts_field, ts_type},
};

/// 生成 mml-ipc/src/types/ 下的类型文件与入口 types/index.ts
///
/// 一个来源 .rs 文件一个 .ts，目录结构与 src/ 一致；跨文件的类型引用自动补 import type。
///
/// - groups: 输出模块路径（相对 types/，如 dtos/instance_dto.ts）-> 该文件的类型声明
/// - ext: 外部 crate 的类型映射，透传给 ts_field
///
/// # 返回值
///
/// 每个类型文件一项，最后是 barrel index；rel_path 相对 mml-ipc/src
pub(crate) fn type_files(
    groups: &BTreeMap<String, Vec<Decl>>,
    ext: &BTreeMap<String, String>,
) -> Vec<GeneratedFile> {
    let name_to_path: BTreeMap<String, String> = groups
        .iter()
        .flat_map(|(path, decls)| decls.iter().map(move |d| (d.name.clone(), path.clone())))
        .collect();

    let mut files = Vec::new();
    for (path, decls) in groups {
        let body = types_body(decls, ext);
        let mut content = String::from(HEADER);
        for (target, names) in referenced_imports(&body, path, &name_to_path) {
            let names = names.into_iter().collect::<Vec<_>>().join(", ");
            content.push_str(&format!(
                "import type {{ {names} }} from \"{}\";\n",
                relative_specifier(path, &target)
            ));
        }
        if content != HEADER {
            content.push('\n');
        }
        content.push_str(&body);
        files.push(GeneratedFile {
            rel_path: format!("types/{path}"),
            content,
        });
    }

    // barrel：bindings.ts 只要 export * from "./types"
    let mut index = String::from(HEADER);
    for path in groups.keys() {
        index.push_str(&format!(
            "export * from \"./{}\";\n",
            path.trim_end_matches(".ts")
        ));
    }
    files.push(GeneratedFile {
        rel_path: "types/index.ts".into(),
        content: index,
    });
    files
}

/// 生成 mml-ipc/src/bindings.ts：命令包装 + 再导出 types/
///
/// 命令签名里用到的类型既要 export * 出去，也要 import 进本文件才能当泛型用。
///
/// - sigs: 命令签名，已按模块与名字排序
/// - declared: 全部生成的类型名，用来挑出本文件要 import 的
///
/// # 返回值
///
/// 整个文件内容，头部带"勿手改"标记
pub(crate) fn bindings_ts(sigs: &[Sig], declared: &BTreeSet<String>) -> String {
    let mut body = String::new();
    append_commands(&mut body, sigs);

    let imports: Vec<String> = identifiers(&body)
        .into_iter()
        .filter(|id| declared.contains(*id))
        .map(|s| s.to_string())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();

    let mut b = String::from(
        "// @generated by ipc-gen（由 mml-gui/src-tauri/build.rs 调用）—— 勿手改\n\
         //\n\
         // 命令包装；跨 IPC 类型按来源 .rs 拆在 types/ 下，这里统一再导出。\n\
         // 传输层不在这里绑定：createCommands 接收调用方传入的 invoke。\n\n\
         import type { Invoke } from \"./invoke\";\n",
    );
    if !imports.is_empty() {
        b.push_str(&format!(
            "import type {{ {} }} from \"./types\";\n",
            imports.join(", ")
        ));
    }
    b.push_str("\nexport * from \"./types\";\n\n");
    b.push_str(&body);
    b
}

/// 生成 mml-ipc/src/listens.ts：事件名常量 + EventPayloads + createEvents
///
/// 除了名字，还给每个事件生成一个 onXxx 订阅函数；payload 类型来自发射函数的实参。
///
/// - events: 扫描到的事件，已按事件名排序去重
/// - ext: 外部 crate 的类型映射，透传给 ts_type
/// - declared: 全部生成的类型名，用来决定 listens.ts 要 import 哪些
///
/// # 返回值
///
/// 整个文件内容，头部带"勿手改"标记
pub(crate) fn listens_ts(
    events: &[ScannedEvent],
    ext: &BTreeMap<String, String>,
    declared: &BTreeSet<String>,
) -> String {
    let mut imports: BTreeSet<String> = BTreeSet::new();
    let mut items: Vec<(String, String, String)> = Vec::new();
    for e in events {
        let event = e.event_name();
        let payload = match &e.payload {
            Some(ty) => ts_type(ty, ext),
            None => "void".to_string(),
        };
        for id in identifiers(&payload) {
            if declared.contains(id) {
                imports.insert(id.to_string());
            }
        }
        items.push((event, pascal(&e.event_name()), payload));
    }

    let mut ts = String::from(
        "// @generated by ipc-gen（由 mml-gui/src-tauri/build.rs 调用）—— 勿手改，新增事件请给函数加 gui_macros::emit 标记\n\n",
    );
    if !imports.is_empty() {
        ts.push_str(&format!(
            "import type {{ {} }} from \"./bindings\";\n\n",
            imports.into_iter().collect::<Vec<_>>().join(", ")
        ));
    }

    for (event, const_name, _) in &items {
        ts.push_str(&format!("export const {const_name} = \"{event}\"\n"));
    }
    ts.push('\n');

    ts.push_str("/** 事件名 -> payload 类型；无 payload 的事件是 void */\n");
    ts.push_str("export interface EventPayloads {\n");
    for (_, const_name, payload) in &items {
        ts.push_str(&format!("  [{const_name}]: {payload};\n"));
    }
    ts.push_str("}\n\n");

    ts.push_str("/** 订阅传输层：命令的 invoke 对应这里的 on，由调用方给 */\n");
    ts.push_str("// eslint-disable-next-line @typescript-eslint/no-explicit-any\n");
    ts.push_str(
        "export type EventOn = (event: string, cb: (payload: any) => void) => () => void;\n\n",
    );

    ts.push_str("/**\n");
    ts.push_str(" * 按事件创建订阅函数，每个事件一个带 payload 类型的 onXxx\n");
    ts.push_str(" *\n");
    ts.push_str(" * - on: 订阅函数；Tauri 页面传 listen 的同步包装，自定义主页传 window.mml.on\n");
    ts.push_str(" *\n");
    ts.push_str(" * # 返回值\n");
    ts.push_str(" *\n");
    ts.push_str(" * 各 onXxx(cb)；返回的取消订阅函数要在页面 / 组件卸载时调用\n");
    ts.push_str(" */\n");
    ts.push_str("export function createEvents(on: EventOn) {\n");
    ts.push_str("  return {\n");
    for (_, const_name, payload) in &items {
        let cb = if payload == "void" {
            "() => void".to_string()
        } else {
            format!("(payload: {payload}) => void")
        };
        ts.push_str(&format!(
            "    on{const_name}: (cb: {cb}) => on({const_name}, cb),\n"
        ));
    }
    ts.push_str("  };\n");
    ts.push_str("}\n");
    ts
}

/// 生成文件的头部注释
const HEADER: &str = "// @generated by ipc-gen（由 mml-gui/src-tauri/build.rs 调用）—— 勿手改\n\n";

/// 追加命令表：按来源 .rs 模块分组；按 AGENTS §4，命令名 = 窗口名_方法名，
/// 所以同一文件里的命令共享同一个前段；把它剥掉，组内只剩方法名
///
/// - b: 输出缓冲，追加写入
/// - sigs: 命令签名，已按模块与名字排序
fn append_commands(b: &mut String, sigs: &[Sig]) {
    b.push_str("/** 创建命令包装：传入传输层的 invoke，Tauri 页面与自定义主页各用各的 */\n");
    b.push_str("export function createCommands(invoke: Invoke) {\n");
    b.push_str("  return {\n");

    // 归组：组键 = 显式分组标记或来源模块最后一段。
    // 输出顺序沿用"组键首次出现"的顺序，不按组键排序。
    let mut order: Vec<String> = Vec::new();
    let mut grouped: BTreeMap<String, Vec<&Sig>> = BTreeMap::new();
    for s in sigs {
        let key = s.group_key().to_string();
        if !grouped.contains_key(&key) {
            order.push(key.clone());
        }
        grouped.entry(key).or_default().push(s);
    }

    for key in order {
        let group = &grouped[&key];
        let group_key = camel(&key);

        // 组内命令名的公共前段，按 _ 分段取最长公共前缀
        let segs = |n: &str| n.split('_').map(|s| s.to_string()).collect::<Vec<_>>();
        let mut common = segs(&group[0].name);
        for s in group {
            let other = segs(&s.name);
            let mut k = 0;
            while k < common.len() && k < other.len() && common[k] == other[k] {
                k += 1;
            }
            common.truncate(k);
        }
        // 公共前缀不能吃掉整个名字，否则方法名会空；单命令组会走到这里
        let mut strip_len = common.len();
        if strip_len > 0 && group.iter().any(|s| segs(&s.name).len() == strip_len) {
            strip_len -= 1;
        }
        let strip = if strip_len == 0 {
            None
        } else {
            Some(common[..strip_len].join("_") + "_")
        };

        b.push_str(&format!("    {group_key}: {{\n"));

        // 组内按最终方法名排序：命令在文件之间怎么搬都不影响生成结果
        let mut entries: Vec<(String, &Sig)> = group
            .iter()
            .map(|s| {
                let method = camel(match &strip {
                    Some(prefix) => s.name.strip_prefix(prefix).unwrap_or(&s.name),
                    None => s.name.as_str(),
                });
                (method, *s)
            })
            .collect();
        entries.sort_by(|a, b| a.0.cmp(&b.0));

        for (method, s) in entries {
            let name = &s.name;
            let ret = &s.ret;
            let list = s
                .params
                .iter()
                .map(|p| {
                    format!(
                        "{}{}: {}",
                        p.name,
                        if p.optional { "?" } else { "" },
                        p.ty
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            let arg = if s.params.is_empty() {
                String::new()
            } else {
                let obj = s
                    .params
                    .iter()
                    .map(|p| p.name.clone())
                    .collect::<Vec<_>>()
                    .join(", ");
                format!(", {{ {obj} }}")
            };
            b.push_str(&format!(
                "      {method}: ({list}) => invoke<{ret}>(\"{name}\"{arg}),\n"
            ));
        }
        b.push_str("    },\n");
    }
    b.push_str("  };\n}\n\n");
}

/// 变体名的 camelCase：只把首字母小写，与 serde 对变体的处理一致
///
/// - `name`: Rust 变体名，如 `Home` / `HomePage`
///
/// # 返回值
///
/// 首字母小写后的名字
fn lower_first(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_ascii_lowercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

/// 类型文件正文：枚举生成字符串联合，struct 逐字段转 TS，serde 命名风格生效
///
/// - decls: 该文件里的类型声明
/// - ext: 外部 crate 的类型映射，透传给 ts_field
fn types_body(decls: &[Decl], ext: &BTreeMap<String, String>) -> String {
    let mut b = String::new();
    for d in decls {
        let rename_all = rename_all_of(&d.attrs);
        if d.is_enum {
            let variants: Vec<String> = split_top_level(&d.body)
                .into_iter()
                .filter_map(|v| {
                    // 跳过变体前置的文档注释与属性，如 #[default]，再取标识符
                    let line = v
                        .lines()
                        .map(|l| l.trim())
                        .find(|l| !l.is_empty() && !l.starts_with("//") && !l.starts_with("#["))?;
                    let name: String = line
                        .chars()
                        .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                        .collect();
                    if name.is_empty() {
                        return None;
                    }
                    Some(match rename_all.as_deref() {
                        Some("lowercase") => name.to_ascii_lowercase(),
                        // serde 的 camelCase 对变体只把首字母小写，Home -> home，不是字段那套下划线转驼峰
                        Some("camelCase") => lower_first(&name),
                        _ => name,
                    })
                })
                .collect();
            b.push_str(&format!(
                "export type {} = {};\n\n",
                d.name,
                variants
                    .iter()
                    .map(|v| format!("\"{v}\""))
                    .collect::<Vec<_>>()
                    .join(" | ")
            ));
            continue;
        }

        // 只 derive Deserialize = 前端传给后端的入参 DTO，字段可缺省，见 ts_field
        let input_only = !d.attrs.contains("Serialize");
        b.push_str(&format!("export type {} = {{\n", d.name));
        for line in d.body.lines() {
            let line = line.trim();
            if line.starts_with("//") || line.starts_with("#[") || line.is_empty() {
                continue;
            }
            let Some((raw_name, raw_ty)) = line.split_once(':') else {
                continue;
            };
            let raw_name = raw_name.trim().trim_start_matches("pub ").trim();
            if raw_name.is_empty() || raw_name.starts_with('/') {
                continue;
            }
            let raw_name = raw_name.trim_start_matches("r#");
            let raw_ty = raw_ty.trim().trim_end_matches(',').trim();
            let ts_name = match rename_all.as_deref() {
                Some("camelCase") => camel(raw_name),
                Some("lowercase") => raw_name.to_ascii_lowercase(),
                _ => raw_name.to_string(),
            };
            let field = ts_field(raw_ty, input_only, ext);
            b.push_str(&format!(
                "  {ts_name}{}: {},\n",
                if field.optional { "?" } else { "" },
                field.ty
            ));
        }
        b.push_str("};\n\n");
    }
    b
}

/// 正文里引用了哪些别的类型文件里的类型
///
/// 只看生成的类型定义，字段名是小驼峰、类型名是大驼峰，不会互相误判；枚举值先掐掉。
///
/// - body: 类型定义正文
/// - this: 当前文件模块路径
/// - name_to_path: 类型名 -> 所属文件模块路径
///
/// # 返回值
///
/// 目标文件 -> 需要 import 的类型名集合
fn referenced_imports(
    body: &str,
    this: &str,
    name_to_path: &BTreeMap<String, String>,
) -> BTreeMap<String, BTreeSet<String>> {
    let stripped = strip_strings(body);
    let mut out: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for id in identifiers(&stripped) {
        if let Some(path) = name_to_path.get(id) {
            if path != this {
                out.entry(path.clone()).or_default().insert(id.to_string());
            }
        }
    }
    out
}

/// from 模块 import to 模块的相对路径，如 dtos/a.ts -> dtos/b.ts 是 ./b
///
/// - from: 当前模块路径，相对 types/
/// - to: 目标模块路径，相对 types/
///
/// # 返回值
///
/// 不带 .ts 后缀的相对引用
fn relative_specifier(from: &str, to: &str) -> String {
    let from_parts: Vec<&str> = from.split('/').collect();
    let to_parts: Vec<&str> = to.split('/').collect();
    let from_dir = &from_parts[..from_parts.len() - 1];
    let to_dir = &to_parts[..to_parts.len() - 1];

    let mut common = 0;
    while common < from_dir.len() && common < to_dir.len() && from_dir[common] == to_dir[common] {
        common += 1;
    }

    let mut spec = if from_dir.len() == common {
        String::from("./")
    } else {
        "../".repeat(from_dir.len() - common)
    };
    if to_dir.len() > common {
        spec.push_str(&to_dir[common..].join("/"));
        spec.push('/');
    }
    spec.push_str(to_parts.last().unwrap().trim_end_matches(".ts"));
    spec
}

/// 取一段 TS 里的标识符
fn identifiers(ts: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut rest = ts;
    while let Some(pos) = rest.find(|c: char| c.is_ascii_alphabetic() || c == '_') {
        let tail = &rest[pos..];
        let len = tail
            .bytes()
            .take_while(|b| b.is_ascii_alphanumeric() || *b == b'_')
            .count();
        if len == 0 {
            break;
        }
        out.push(&tail[..len]);
        rest = &tail[len..];
    }
    out
}

/// 去掉 TS 里双引号字符串的内容，枚举值不会误判成类型名
fn strip_strings(ts: &str) -> String {
    let mut out = String::new();
    let mut in_str = false;
    let mut escaped = false;
    for c in ts.chars() {
        if in_str {
            if escaped {
                escaped = false;
            } else if c == '\\' {
                escaped = true;
            } else if c == '"' {
                in_str = false;
            }
            continue;
        }
        if c == '"' {
            in_str = true;
            continue;
        }
        out.push(c);
    }
    out
}

