//! 生成 `$OUT_DIR/invokes_gen.rs`：`listens` 常量 + `tauri_commands!` 注册宏

use crate::{CommandRef, scan::ScannedEvent, ts::screaming};

/// 生成 `invokes_gen.rs` 的正文：`listens` 常量模块 + `tauri_commands!` 注册宏
///
/// - `events`: 扫描到的事件，已按事件名排序去重；这里只用到事件名
/// - `commands`: 命令名与 Rust 路径，按 (名, 路径) 排好序，见 [`CommandRef`]
///
/// # 返回值
///
/// 整个文件内容，头部带"勿手改"标记
pub(crate) fn invokes_gen(events: &[ScannedEvent], commands: &[CommandRef]) -> String {
    let mut rs = String::from("// @generated by build.rs，扫描 src/ 收集 —— 勿手改\n\n");

    rs.push_str("pub mod listens {\n");
    for event in events {
        let name = event.event_name();
        rs.push_str(&format!(
            "    pub const {}: &str = \"{}\";\n",
            screaming(&name),
            name
        ));
    }
    rs.push_str("}\n\n");

    // 命令注册宏：lib.rs 里 invoke_handler(tauri_commands!())
    rs.push_str("/// generate_handler 注册表，扫描 src/ 生成\n");
    rs.push_str("#[macro_export]\nmacro_rules! tauri_commands {\n");
    rs.push_str("    () => {\n        tauri::generate_handler![\n");
    for cmd in commands {
        rs.push_str(&format!("            {},\n", cmd.path));
    }
    rs.push_str("        ]\n    };\n}\n");

    rs
}
