#!/usr/bin/env bash
# 用已构建的 target/release/mml-gui 打 Arch 包（.pkg.tar.zst），不重新编译。
# 不依赖 makepkg / Arch：Arch 包就是 tar.zst 里放 .PKGINFO（可选 .MTREE），
# 在 Ubuntu 上也能直接打；有 bsdtar 时顺带生成 .MTREE。
#
# 用法：bash build/package-arch.sh
# 产物：build_out/mml-arch-<arch>-<version>.pkg.tar.zst

set -euo pipefail
# 包内目录固定 755；本机 umask 0002 时新建的父目录会变成 775
umask 022

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
version="$(tr -d '[:space:]' < "$root/build/version")"

binary="$root/target/release/mml-gui"
if [ ! -f "$binary" ]; then
    echo "找不到 $binary，请先跑 build/build-release.sh。" >&2
    exit 1
fi

case "$(uname -m)" in
    x86_64) host_arch=x86_64; label=x64 ;;
    aarch64|arm64) host_arch=aarch64; label=arm64 ;;
    *) echo "不支持的架构：$(uname -m)" >&2; exit 1 ;;
esac

work="$root/target/package/arch"
pkgroot="$work/pkg"
rm -rf "$work"
install -d -m755 "$pkgroot/usr/bin" \
    "$pkgroot/usr/share/applications" \
    "$pkgroot/usr/share/icons/hicolor/256x256/apps" \
    "$pkgroot/usr/share/metainfo" \
    "$pkgroot/usr/share/licenses/mml-gui"

install -m755 "$binary" "$pkgroot/usr/bin/mml-gui"
install -m644 "$root/build/linux/com.coloryr.mml.desktop" \
    "$pkgroot/usr/share/applications/com.coloryr.mml.desktop"
install -m644 "$root/mml-gui/src-tauri/icons/128x128@2x.png" \
    "$pkgroot/usr/share/icons/hicolor/256x256/apps/com.coloryr.mml.png"
install -m644 "$root/build/linux/com.coloryr.mml.metainfo.xml" \
    "$pkgroot/usr/share/metainfo/com.coloryr.mml.metainfo.xml"
install -m644 "$root/LICENSE" "$pkgroot/usr/share/licenses/mml-gui/LICENSE"

size="$(find "$pkgroot" -type f -printf '%s\n' | awk '{ sum += $1 } END { print sum + 0 }')"
builddate="$(date +%s)"

cat > "$pkgroot/.PKGINFO" <<EOF
# Generated by M²L build/package-arch.sh
pkgname = mml-gui
pkgbase = mml-gui
pkgver = $version-1
pkgdesc = M²L Minecraft Launcher
url = https://github.com/Coloryr/ModernMinecraftLauncher
builddate = $builddate
packager = M²L
size = $size
arch = $host_arch
license = Apache-2.0
depend = glibc
depend = libgcc
depend = glib2
depend = dbus
depend = cairo
depend = gdk-pixbuf2
depend = libsoup3
depend = fontconfig
depend = gtk3
depend = webkit2gtk-4.1
depend = hicolor-icon-theme
optdepend = libayatana-appindicator: tray icon
EOF

out="$root/build_out/mml-arch-$label-$version.pkg.tar.zst"
mkdir -p "$root/build_out"
rm -f "$out"

if command -v bsdtar >/dev/null 2>&1; then
    (cd "$pkgroot" && bsdtar -czf .MTREE --format=mtree --uid 0 --gid 0 \
        --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO usr)
    (cd "$pkgroot" && bsdtar --zstd -cf "$out" --uid 0 --gid 0 .PKGINFO .MTREE usr)
else
    echo '未找到 bsdtar，跳过 .MTREE（pacman 仍可安装）。' >&2
    (cd "$pkgroot" && tar --zstd --owner=0 --group=0 --numeric-owner -cf "$out" .PKGINFO usr)
fi

echo "已生成：${out#"$root"/}"
