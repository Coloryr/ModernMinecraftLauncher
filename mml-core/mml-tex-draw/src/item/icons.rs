///
/// - `id`: 物品ID，不带命名空间
pub(crate) fn item_cat(id: &str) -> Option<&'static str> {
    ITEM_ICONS
        .iter()
        .find(|(name, _)| *name == id)
        .map(|(_, cat)| *cat)
}
