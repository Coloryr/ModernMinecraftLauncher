/* eslint-disable no-console */
// 生成 mml-vue 的 UI 出口（在仓库根或 mml-vue 下都能跑）
//
//   node mml-vue/scripts/gen-ui.ts
//
// 产物都在 mml-vue/src/generated，由 package.json 的 exports 暴露：
//   mml-vue/ui-kit             控件 + 清单 + v-tip + 自定义界面类型
//   mml-vue/ui-kit.css         主题变量 + 控件外观
//   mml-vue/ui-kit/controls    控件清单（Node 只取清单时不必加载 .vue）
//   mml-vue/ui-kit/windows     全部窗口与窗口内部组件
//   mml-vue/ui-kit/components  其余通用组件
//
// 两个示例按 file:../mml-vue 依赖，不再有单独的 kit 包；发布也只发 mml-vue。

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = "// @generated by mml-vue/scripts/gen-ui.ts —— 勿手改";
const CSS_HEADER = "/* @generated by mml-vue/scripts/gen-ui.ts —— 勿手改 */";

const COMPONENTS = [
  "BaseButton",
  "BaseSwitch",
  "SegmentedTabs",
  "NumberStepper",
  "SearchBox",
  "CollapsePanel",
  "GlyphIcon",
  "LaunchProgress",
];

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(root, "src");
const outDir = join(sourceRoot, "generated");

interface ControlEntry {
  className: string;
  category: string;
  count: number;
  sources: string[];
}

interface VariableEntry {
  name: string;
  description: string;
}

function collect(dir: string, out: string[]): void {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) collect(full, out);
    else if (extname(entry.name) === ".css") out.push(full);
  }
}

function selectors(css: string): string[] {
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const out: string[] = [];
  for (const chunk of clean.split("}")) {
    const brace = chunk.indexOf("{");
    if (brace >= 0) out.push(chunk.slice(0, brace));
  }
  return out;
}

const CLASS_RE = /\.(-?[_a-zA-Z][\w-]*)/g;

function categoryOf(rel: string): string {
  if (rel === "styles/controls.css") return "控件";
  if (rel === "styles/themes.css") return "主题";
  if (rel === "styles/titlebar.css") return "标题栏";
  if (rel.startsWith("styles/parts/")) return "部件";
  if (rel.startsWith("styles/")) return rel.slice("styles/".length).replace(/\.css$/, "");
  if (rel.startsWith("windows/")) return "窗口：" + (rel.split("/")[1] ?? "windows");
  return "组件";
}

function scanControls(files: string[]): ControlEntry[] {
  const found = new Map<string, ControlEntry>();
  for (const file of files) {
    const css = readFileSync(file, "utf8");
    if (!css.trim()) continue;
    const rel = relative(sourceRoot, file).replace(/\\/g, "/");
    for (const selector of selectors(css)) {
      for (const match of selector.matchAll(CLASS_RE)) {
        const className = match[1];
        const hit = found.get(className);
        if (hit) {
          hit.count += 1;
          if (!hit.sources.includes(rel)) hit.sources.push(rel);
        } else {
          found.set(className, { className, category: categoryOf(rel), count: 1, sources: [rel] });
        }
      }
    }
  }
  return [...found.values()].sort((a, b) => a.className.localeCompare(b.className));
}

function scanVariables(css: string): VariableEntry[] {
  const out: VariableEntry[] = [];
  let comment = "";
  for (const line of css.split("\n")) {
    const trimmed = line.trim();
    if (trimmed.startsWith("/*")) {
      comment = trimmed.replace(/^\/+\*+/, "").replace(/\*+\/+$/, "").trim();
      continue;
    }
    if (trimmed.startsWith("*")) {
      const text = trimmed.replace(/^\*+\s*/, "").trim();
      if (text && text !== "*/") comment = text;
      continue;
    }
    const match = /^(--[\w-]+)\s*:\s*(.+?);/.exec(trimmed);
    if (match) out.push({ name: match[1], description: comment });
  }
  return out;
}

function mergeVariables(groups: VariableEntry[][]): VariableEntry[] {
  const seen = new Set<string>();
  const out: VariableEntry[] = [];
  for (const group of groups) {
    for (const item of group) {
      if (seen.has(item.name)) continue;
      seen.add(item.name);
      out.push(item);
    }
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

function emitControls(controls: ControlEntry[], variables: VariableEntry[]): string {
  const lines: string[] = [HEADER, ""];
  lines.push("/** 一个可被自定义 CSS 选中的类 */");
  lines.push("export interface ControlEntry {");
  lines.push("  className: string;");
  lines.push("  category: string;");
  lines.push("  count: number;");
  lines.push("  sources: string[];");
  lines.push("}");
  lines.push("");
  lines.push("export const CONTROLS: ControlEntry[] = [");
  for (const item of controls) {
    lines.push("  { className: " + JSON.stringify(item.className) +
      ", category: " + JSON.stringify(item.category) +
      ", count: " + item.count +
      ", sources: " + JSON.stringify(item.sources) + " },");
  }
  lines.push("];");
  lines.push("");
  lines.push("export interface CssVariable {");
  lines.push("  name: string;");
  lines.push("  description: string;");
  lines.push("}");
  lines.push("");
  lines.push("export const CSS_VARIABLES: CssVariable[] = [");
  for (const item of variables) {
    lines.push("  { name: " + JSON.stringify(item.name) + ", description: " + JSON.stringify(item.description) + " },");
  }
  lines.push("];");
  return lines.join("\n") + "\n";
}

function componentRel(name: string): string {
  if (existsSync(join(sourceRoot, "components", "ui", name + ".vue"))) {
    return "../components/ui/" + name + ".vue";
  }
  if (existsSync(join(sourceRoot, "components", name + ".vue"))) {
    return "../components/" + name + ".vue";
  }
  console.error("✗ 找不到控件：" + name);
  process.exit(1);
}

function emitUiKit(): string {
  const lines: string[] = [HEADER, "", "// 启动器控件的对外出口", ""];
  for (const name of COMPONENTS) {
    const alias = "Kit" + name.replace(/^Base/, "");
    lines.push("export { default as " + alias + " } from \"" + componentRel(name) + "\";");
  }
  lines.push("export * from \"./controls\";");
  lines.push("export { vTip as tipDirective } from \"../lib/tip\";");
  lines.push("export type { CustomCssContext, CustomCssReplaceOptions, WindowPageRegistry } from \"mml-ipc\";");
  return lines.join("\n") + "\n";
}

function emitCss(): string {
  return CSS_HEADER + "\n\n" +
    "@import \"../styles/themes.css\";\n" +
    "@import \"../styles/controls.css\";\n";
}

function listVue(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listVue(full));
    else if (entry.name.endsWith(".vue")) out.push(full);
  }
  return out.sort();
}

function pascal(text: string): string {
  return text.split(/[-_/]/).filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function windowAlias(rel: string): string {
  const stem = rel.split("/").pop()!.replace(/\.vue$/, "");
  if (stem.endsWith("Window")) return stem;
  return "Win" + rel.replace(/\.vue$/, "").split("/").map(pascal).join("");
}

function emitWindows(): string {
  const base = join(sourceRoot, "windows");
  const lines: string[] = [
    HEADER,
    "",
    "/// <reference path=\"../types/monaco-diff.d.ts\" />",
    "/// <reference path=\"../types/monaco-languages.d.ts\" />",
    "",
    "// 全部窗口与窗口内部组件",
    "",
  ];
  for (const file of listVue(base)) {
    const rel = relative(base, file).replace(/\\/g, "/");
    lines.push("export { default as " + windowAlias(rel) + " } from \"../windows/" + rel + "\";");
  }
  return lines.join("\n") + "\n";
}

function emitComponents(): string {
  const base = join(sourceRoot, "components");
  const lines: string[] = [HEADER, "", "// 8 个已导出控件之外的其余通用组件", ""];
  for (const file of listVue(base)) {
    const rel = relative(base, file).replace(/\\/g, "/");
    const stem = rel.split("/").pop()!.replace(/\.vue$/, "");
    if (COMPONENTS.includes(stem)) continue;
    lines.push("export { default as Comp" + rel.replace(/\.vue$/, "").split("/").map(pascal).join("") +
      " } from \"../components/" + rel + "\";");
  }
  return lines.join("\n") + "\n";
}

function write(path: string, text: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

if (!existsSync(sourceRoot)) {
  console.error("✗ 找不到 mml-vue/src");
  process.exit(1);
}

const files: string[] = [];
collect(sourceRoot, files);
const controls = scanControls(files);
const variables = mergeVariables([
  scanVariables(readFileSync(join(sourceRoot, "styles", "themes.css"), "utf8")),
  scanVariables(readFileSync(join(sourceRoot, "styles", "controls.css"), "utf8")),
]);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

write(join(outDir, "controls.ts"), emitControls(controls, variables));
write(join(outDir, "ui-kit.ts"), emitUiKit());
write(join(outDir, "ui-kit.css"), emitCss());
write(join(outDir, "windows.ts"), emitWindows());
write(join(outDir, "components.ts"), emitComponents());

console.log("✓ 生成 mml-vue/ui-kit：" + controls.length + " 个类选择器，" + variables.length + " 个变量，" + COMPONENTS.length + " 个控件");
